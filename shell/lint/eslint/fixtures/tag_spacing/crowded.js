/** @file A blank line between parameters, none before @returns, and two before it. */

/**
 * Adds two numbers.
 *
 * @param a The first.
 *
 * @param b The second.
 * @returns Their sum.
 */
export function add(a, b) {
  return a + b;
}

/**
 * Doubles a number.
 *
 * @param value The number.
 *
 *
 * @returns Twice it.
 */
export function double(value) {
  return value * 2;
}
