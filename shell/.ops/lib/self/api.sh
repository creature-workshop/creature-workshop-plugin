#!/bin/sh

: <<'MODULE'
shellops self-management API.

`ops install` provisions tools whose bin dirs are not on a default PATH (cargo,
uv, go, zig...). Rather than each runner needing its own PATH plumbing
($GITHUB_PATH on GitHub, nothing on GitLab), shellops records each provisioned
bin dir — and any variable a tool reads to find its own install, such as
CARGO_HOME — into $PROJ/.ops/cache/env.sh: a sourced fragment that .envrc loads,
so every action and CI step sees the tools with no per-action PATH patching.
A path under $PROJ is recorded from ${PROJ} rather than spelled out, so the
fragment holds wherever the checkout lands -- a CI cache restored under a
renamed group path still resolves.

It also decides where those tools live: every channel derives its default
install location from self__tool_home, so one root variable moves them all.
MODULE

: <<'PUB_FUN'
Record a bin dir on PATH for every shell that sources .envrc. Idempotent — a
dir already recorded is not appended twice.

args:
  $1  The bin directory to prepend to PATH
PUB_FUN
self__add_persistent_path() {
  [ -n "$1" ] || return 0

  __self__append_export "export PATH=\"$(__self__portable_path "$1"):\$PATH\""
}

: <<'PUB_FUN'
Record an environment variable for every shell that sources .envrc, so the job
step after an installer reads the value that installer picked. Idempotent — a
name and value already recorded are not appended twice.

    PROJ=/p self__add_persistent_env CARGO_HOME /p/.ops/cache/tools/cargo
    # appends: export CARGO_HOME="${PROJ}/.ops/cache/tools/cargo"

args:
  $1  The variable name
  $2  The value to export
PUB_FUN
self__add_persistent_env() {
  [ -n "$1" ] || return 0

  __self__append_export "export ${1}=\"$(__self__portable_path "$2")\""
}

: <<'FUN'
Print a path as env.sh records it: under $PROJ it is spelled from ${PROJ},
which .envrc has set by the time it sources the fragment; anywhere else it is
unchanged.

    PROJ=/p __self__portable_path /p/.ops/cache/tools/fnm  ->  ${PROJ}/.ops/cache/tools/fnm
    PROJ=/p __self__portable_path /root/.cargo/bin        ->  /root/.cargo/bin

args:
  $1  The path to record
FUN
__self__portable_path() {
  __self__portable_path__root="${PROJ:-.}"

  case "$1" in
    "$__self__portable_path__root"/*)
      printf '${PROJ}%s\n' "${1#"$__self__portable_path__root"}"
      ;;
    *)
      println "$1"
      ;;
  esac
}

: <<'FUN'
Append one export line to .ops/cache/env.sh, the fragment .envrc sources, unless
that exact line is in the file already. Creates .ops/cache (and a header) on
first use.

args:
  $1  The export line to append
FUN
__self__append_export() {
  __self__append_export__cache="${PROJ:-.}/.ops/cache"
  __self__append_export__file="$__self__append_export__cache/env.sh"

  mkdir -p "$__self__append_export__cache"

  if [ ! -f "$__self__append_export__file" ]; then
    println '# Generated by ops install. Environment for provisioned tools; sourced by .envrc.' \
      > "$__self__append_export__file"
  fi

  if grep -qF "$1" "$__self__append_export__file"; then
    return 0
  fi

  println "$1" >> "$__self__append_export__file"
}

: <<'PUB_FUN'
Prints the home directory for a provisioned tool. In a developer shell that is
the tool's dot-dir in $HOME. When SHELLOPS_TOOLS_HOME is set it is the same
name without the dot under that root, so a CI job that points the root at a
cached directory carries every tool in one place. Channels and libs derive
their default install location from this rather than from $HOME, and an
explicit per-tool override (NODE_FNM_HOME, ZIGBUILD_ZIG_HOME...) still wins.

    self__tool_home .fnm                                        ->  /home/me/.fnm
    SHELLOPS_TOOLS_HOME=/p/.ops/cache/tools self__tool_home .fnm  ->  /p/.ops/cache/tools/fnm
    SHELLOPS_TOOLS_HOME=/p/.ops/cache/tools self__tool_home go    ->  /p/.ops/cache/tools/go

args:
  $1  The tool's directory name as it sits in $HOME (.fnm, .zig, go)
PUB_FUN
self__tool_home() {
  if [ -n "${SHELLOPS_TOOLS_HOME:-}" ]; then
    printf '%s/%s\n' "$SHELLOPS_TOOLS_HOME" "${1#.}"
  else
    printf '%s/%s\n' "$HOME" "$1"
  fi
}
